// Where the app's rule-based figures actually come from.
//
// This app tells people what their taxes, RMDs, Medicare surcharges and
// estate liability will be. Every one of those rests on a statutory figure
// somebody typed into calculator.js, and until now there was almost no way
// for a user -- or the advisor they were told to consult -- to check any of
// it. Three ssa.gov links and one irs.gov link existed in the whole app.
//
// This is the natural other half of the disclaimer. "Not advice" says what
// the output isn't; this says exactly where each rule came from, so a
// skeptical reader can go and verify it rather than taking it on trust.
//
// Two rules for anything added here:
//
// 1. FIRST-PARTY ONLY. Links go to the agency that sets the rule -- IRS,
//    SSA, CMS/Medicare -- never to a summary, a brokerage explainer, or a
//    news article. Those move, sell things, and get the details wrong.
//    sources.test.js enforces the domain list.
//
// 2. VERIFIED, NOT PLAUSIBLE. Every URL below was fetched and its content
//    confirmed to say what it is cited for, on the date recorded. An
//    unverified citation in a credibility feature is worse than no citation
//    -- it invites trust it hasn't earned. Anything not yet checked belongs
//    in UNCITED below, not in this list.
//
// Prefer stable topic pages over annual announcement URLs. The newsroom
// posts that carry each year's numbers are replaced yearly and rot;
// the topic pages are updated in place. See TAX_UPDATE_PROCESS.md, which
// tracks which figures change each year.

