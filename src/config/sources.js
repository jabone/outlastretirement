// Deliberately listed rather than omitted. A sources section that quietly
// covers six of a dozen figures reads as complete and isn't -- naming the
// gaps is the difference between a citation list and a marketing claim.
// Each of these has a source; none has been fetched and confirmed yet, so
// none is linked.
// One entry left, and it is here to stay rather than because nobody has got
// to it. There is no federal source for state tax law -- fifty legislatures
// write it, and no federal agency has a mandate to compile it. The IRS
// publishes nothing on state brackets; the Census Bureau publishes revenue
// collected, not rates. Anything advertising itself as a single 50-state
// source is a private aggregator, and the closest thing to a semi-official
// one (the Federation of Tax Administrators, the states' own association)
// carries rate tables several years stale.
//
// The defensible answer is per-state citation against each state's own
// department of revenue, with a verified-on date each. That is roughly 50-60
// URLs to track and re-check annually -- a real piece of work, not a
// footnote. Until it exists, saying so plainly beats citing an aggregator
// and letting it read as verified.
// (Virginia became the first state cited per-state, 2026-08-31, against its
// own code and department of taxation -- the model for the rest. Illinois,
// Pennsylvania and New York followed on 2026-09-02 for their retirement-
// income rules specifically; their bracket tables remain uncited.)
