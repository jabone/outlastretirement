export const usd = (n) => `$${Math.round(n).toLocaleString('en-US')}`;
// Dollars and cents, for monthly premiums.
export const usdCents = (n) => `$${Number(n).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

// The ACA premium-credit cliff: 400% of the Federal Poverty Level for a
// household of two (a couple) and one.
export const ACA_CLIFF_COUPLE = ACA_SUBSIDY_CLIFF_FPL_MULTIPLE * getFederalPovertyLevel(2);
export const ACA_CLIFF_SINGLE = ACA_SUBSIDY_CLIFF_FPL_MULTIPLE * getFederalPovertyLevel(1);

// Where the 37% bracket starts: the top of the 35% band.
const topBracketStart = (brackets) => brackets.find((b) => b.rate === 0.35).limit;
export const TOP_RATE_START_MFS = topBracketStart(BRACKETS_MFS);
export const TOP_RATE_START_SINGLE = topBracketStart(BRACKETS_SINGLE);

