function headFor({ path, title, description, css }) {
  return privacyHead
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(title)} — OutlastRetirement</title>`)
    .replace(/<meta name="description" content="[^"]*" \/>/, `<meta name="description" content="${esc(description)}" />`)
    .replace(/<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${BASE}${path}" />`)
    .replace(/(property="og:url" content=")[^"]*/, `$1${BASE}${path}`)
    .replace(/((?:property="og:title"|name="twitter:title") content=")[^"]*/g, `$1${esc(title)} — OutlastRetirement`)
    .replace(/((?:property="og:description"|name="twitter:description") content=")[^"]*/g, `$1${esc(description)}`)
    .replace(/  <!-- This page used to carry[\s\S]*?-->\n/, '  <!-- GENERATED by scripts/generatePublicPages.mjs. Edit the config it names, then run the script. -->\n')
    .replace('</style>', `${css}\n  </style>`);
}

