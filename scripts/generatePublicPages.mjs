//   node scripts/generatePublicPages.mjs          write the pages
//   node scripts/generatePublicPages.mjs --check  exit 1 if any is stale
//
// Generated, like public/premium.html, so the pages cannot drift from the
// app. The styling is the privacy page's head, copied verbatim.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { register } from 'node:module';

// The app's modules import each other without file extensions (Vite
// resolves them); teach Node to do the same for this script.
register('data:text/javascript,' + encodeURIComponent(`
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
export async function resolve(spec, ctx, next) {
  if ((spec.startsWith('./') || spec.startsWith('../')) && !/\\.(m?js|jsx|json)$/.test(spec)) {
    for (const ext of ['.js', '.jsx']) {
      const u = new URL(spec + ext, ctx.parentURL);
      if (existsSync(fileURLToPath(u))) return next(u.href, ctx);
    }
  }
  return next(spec, ctx);
}`));

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
