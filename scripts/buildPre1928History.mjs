#!/usr/bin/env node
// Builds src/config/historicalReturnsPre1928.js -- annual stock, bond and
// inflation figures for 1871-1927 -- from Robert J. Shiller's monthly data
// (changelog 449).
//
//   node scripts/buildPre1928History.mjs <shiller-monthly.csv>
//
// The input is Shiller's "U.S. Stock Markets 1871-Present and CAPE Ratio"
// monthly series as CSV with the columns Date, SP500, Dividend,
// Consumer Price Index, Long Interest Rate (the layout of the tidied copy at
// github.com/datasets/s-and-p-500, data/data.csv). The file itself is not
// kept in the repo; its SHA-256 and the date it was fetched go in the
// generated file's header.
//
// Each calendar year Y, January Y to January Y+1:
//   stocks    (Jan Y+1 price + the year's dividends) / Jan Y price - 1;
//             Shiller's dividend column is an annual rate, so the year's
//             dividends are the average of its twelve monthly values.
//   bonds     a 10-year Treasury bought at January's yield and priced a
//             year later, as a 9-year bond, at the next January's yield:
//             coupon plus price change, annual coupons. Shiller's long
//             rate is the 10-year yield (GS10 from 1953, his sources before).
//   inflation January-to-January change in Shiller's CPI (Warren and
//             Pearson's index before 1913, spliced by Shiller).
// The 1928-on table (Damodaran) uses calendar-year total returns and
// annual-average CPI, so the two are built differently; the splice check in
// historicalReturnsPre1928.test.js compares them over 1928-2022.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export function shillerMonthly(csvText) {
  const [head, ...lines] = csvText.trim().split(/\r?\n/);
  const cols = head.split(',');
  const at = (name) => cols.indexOf(name);
  const iDate = at('Date'); const iP = at('SP500'); const iD = at('Dividend');
  const iC = at('Consumer Price Index'); const iL = at('Long Interest Rate');
  const m = new Map();
  for (const line of lines) {
    const c = line.split(',');
    const [y, mo] = c[iDate].split('-').map(Number);
    m.set(`${y}-${mo}`, { p: +c[iP], d: +c[iD], cpi: +c[iC], rate: +c[iL] });
  }
  return m;
}

const r2 = (x) => Math.round(x * 100) / 100;

export function annualRow(m, y) {
  const a = m.get(`${y}-1`);
  const b = m.get(`${y + 1}-1`);
  if (!a || !b || !(b.cpi > 0) || !(a.rate > 0) || !(b.rate > 0)) return null;
  const divs = [];
  for (let k = 1; k <= 12; k += 1) { const v = m.get(`${y}-${k}`); if (v) divs.push(v.d); }
  const d = divs.reduce((s, v) => s + v, 0) / divs.length;
  const stock = ((b.p + d) / a.p - 1) * 100;
  const y0 = a.rate / 100;
  const y1 = b.rate / 100;
  const price = (y0 / y1) * (1 - (1 + y1) ** -9) + (1 + y1) ** -9;
  const bond = (y0 + price - 1) * 100;
  const infl = (b.cpi / a.cpi - 1) * 100;
  return [y, r2(stock), r2(bond), r2(infl)];
}

if (process.argv[1] && process.argv[1].endsWith('buildPre1928History.mjs')) {
  const file = process.argv[2];
  if (!file) { console.error('usage: node scripts/buildPre1928History.mjs <shiller-monthly.csv>'); process.exit(2); }
  const text = readFileSync(file, 'utf8');
  const sha = createHash('sha256').update(text).digest('hex');
  const m = shillerMonthly(text);
  const rows = [];
  for (let y = 1871; y <= 1927; y += 1) {
    const r = annualRow(m, y);
    if (!r) { console.error(`missing data for ${y}`); process.exit(1); }
    rows.push(r);
  }
  const fetched = process.env.FETCHED_ON || new Date().toISOString().slice(0, 10);
  const out = `// GENERATED by scripts/buildPre1928History.mjs -- do not edit by hand.
//
// Annual US market history before 1928, for the historical starts when a
// plan chooses "since 1871" (changelog 449). One row per calendar year:
// [year, S&P stock total return %, 10-year Treasury total return %,
// inflation %], the same layout as historicalReturns.js.
//
// Source: Robert J. Shiller, "U.S. Stock Markets 1871-Present and CAPE
// Ratio" (Yale University; the data behind Irrational Exuberance), monthly
// stock prices, dividends, the consumer price index and the long-term
// interest rate. Read from the tidied CSV of it at
// github.com/datasets/s-and-p-500 (data/data.csv), fetched ${fetched},
// SHA-256 ${sha}.
// How each figure is built is in the script's header. Before 1913 the CPI
// is Warren and Pearson's price index, spliced by Shiller; the bond return
// is reconstructed from yields.
export const HISTORICAL_RETURNS_PRE1928 = Object.freeze([
${rows.map((r) => `  [${r.join(', ')}],`).join('\n')}
]);

export const PRE1928_FIRST_YEAR = HISTORICAL_RETURNS_PRE1928[0][0];
export const SHILLER_DATA_SHA256 = '${sha}';
`;
  const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'config', 'historicalReturnsPre1928.js');
  writeFileSync(target, out);
  console.log(`Wrote ${rows.length} rows (${rows[0][0]}-${rows.at(-1)[0]}) to ${target}`);
  // The same construction for 1928-2022, kept as a test fixture so the
  // splice check against the Damodaran table runs without the source file.
  const overlap = [];
  for (let y = 1928; y <= 2022; y += 1) { const r = annualRow(m, y); if (r) overlap.push(r); }
  const fixture = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', '__tests__', 'fixtures', 'shillerAnnualOverlap.js');
  writeFileSync(fixture, `// GENERATED by scripts/buildPre1928History.mjs from the same Shiller file
// (SHA-256 ${sha}): 1928-2022 built the pre-1928 way, for the splice check.
export const SHILLER_ANNUAL_OVERLAP = [
${overlap.map((r) => `  [${r.join(', ')}],`).join('\n')}
];
`);
  console.log(`Wrote ${overlap.length} overlap rows to ${fixture}`);
}
