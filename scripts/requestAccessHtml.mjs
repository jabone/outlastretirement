export function requestAccessHtml(indent = '') {
  const buttons = WEBMAIL_SERVICES.map((s, i) => `<a class="btn ${i === 0 ? 'btn-primary' : 'btn-ghost'}" target="_blank" rel="noopener noreferrer" href="${esc(s.url(CONTACT_EMAIL, REQUEST_SUBJECT, REQUEST_BODY))}">Write it in ${esc(s.label)}<span class="visually-hidden"> (opens in a new tab)</span></a>`);
  const lines = [
    '<div class="request-access" id="request-access">',
    '  <h3>Ask for Premium by email</h3>',
    '  <p>Send it from the address you want your key sent to. Nothing is sent from this page, and nothing else is asked.</p>',
    '  <div class="request-box">',
    '    <h4>If you use Gmail, Outlook.com or Yahoo Mail</h4>',
    '    <p>Your mail opens in a new tab with the message already written and addressed. Check it and press Send.</p>',
    '    <div class="request-buttons">',
    ...buttons.map((b) => `      ${b}`),
    '    </div>',
    '  </div>',
    '  <div class="request-box">',
    '    <h4>Any other email (Apple Mail, a work account, your phone)</h4>',
    '    <ol class="request-steps">',
    `      <li>Write to <strong>${esc(CONTACT_EMAIL)}</strong> <button type="button" class="copy-link" data-copy="${esc(CONTACT_EMAIL)}">Copy the address</button></li>`,
    `      <li>Use the subject <strong>${esc(REQUEST_SUBJECT)}</strong> <button type="button" class="copy-link" data-copy="${esc(REQUEST_SUBJECT)}">Copy the subject</button></li>`,
    '      <li>Nothing else is needed: no name, no account, no figures from your plan.</li>',
    '      <li>Send it from the address you want the key sent to. The reply has your key and how to turn it on. To reach us about anything else, write to the same address.</li>',
    '    </ol>',
    '  </div>',
    '</div>',
  ];
  return lines.map((l) => indent + l).join('\n');
}

// index.html is hand-written; these markers hold the generated parts.
const HTML_START = '<!-- request-access:start (generated by scripts/generatePremiumPage.mjs) -->';
const HTML_END = '<!-- request-access:end -->';
const CSS_START = '/* request-access-css:start (generated by scripts/generatePremiumPage.mjs) */';
const CSS_END = '/* request-access-css:end */';

function between(text, start, end, body) {
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a < 0 || b < a) throw new Error(`markers not found: ${start}`);
  const lineStart = text.lastIndexOf('\n', a) + 1;
  const indent = text.slice(lineStart, a);
  return text.slice(0, a + start.length) + '\n' + body(indent) + '\n' + indent + text.slice(b);
}

export function syncIndexHtml(text) {
  let out = between(text, HTML_START, HTML_END, (indent) => requestAccessHtml(indent));
  out = between(out, CSS_START, CSS_END, (indent) => REQUEST_ACCESS_CSS.split('\n').map((l) => indent + l).join('\n'));
  return out;
}

export const INDEX_PATH = join(root, 'index.html');
export const readIndex = () => readFileSync(INDEX_PATH, 'utf8');
