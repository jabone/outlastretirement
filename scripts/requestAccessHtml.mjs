// The "Ask for Premium by email" block for the static site pages (the home
// page and the Free and Premium page), built from the same config and the
// same compose links as the app's RequestAccessPanel.jsx, so every place
// that asks for Premium looks and reads the same.
//
// generatePremiumPage.mjs writes it into public/premium.html; it also keeps
// the copy in index.html current, between the request-access markers
// (syncIndexHtml below), and --check fails when either is stale.
import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { CONTACT_EMAIL, REQUEST_SUBJECT, REQUEST_BODY } = await import(pathToFileURL(join(root, 'src/config/premiumOffering.js')).href);
const { WEBMAIL_SERVICES } = await import(pathToFileURL(join(root, 'src/utils/webmailCompose.js')).href);

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

