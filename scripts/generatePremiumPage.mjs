// Writes public/premium.html, the public "Free and Premium" page, from the
// same config the app uses: FREE_GROUPS (src/config/freeOffering.js) and
// PREMIUM_AREAS (src/config/premiumOffering.js). Generated rather than
// hand-written so the page cannot drift from what the app actually offers.
//
//   node scripts/generatePremiumPage.mjs          write the page
//   node scripts/generatePremiumPage.mjs --check  exit 1 if it is stale
//
// The styling is the privacy page's head, copied verbatim, so the static
// pages stay one family.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { FREE_GROUPS } = await import(pathToFileURL(join(root, 'src/config/freeOffering.js')).href);
const { PREMIUM_AREAS, CONTACT_EMAIL } = await import(pathToFileURL(join(root, 'src/config/premiumOffering.js')).href);
const { SITE_NAV } = await import(pathToFileURL(join(root, 'src/config/siteNav.js')).href);
const { ANALYTICS_SENDS } = await import(pathToFileURL(join(root, 'src/config/analyticsDisclosure.js')).href);

const esc = (s) => String(s)
  .replace(/--/g, '—')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const privacy = readFileSync(join(root, 'public/privacy.html'), 'utf8');
let head = privacy.slice(0, privacy.indexOf('</head>'));
head = head
  .replace(/<title>[^<]*<\/title>/, '<title>Free and Premium — OutlastRetirement</title>')
  .replace(/<meta name="description" content="[^"]*" \/>/, '<meta name="description" content="What the free OutlastRetirement planner includes, and what the optional Premium adds. Both run on your device." />')
  // Canonical and link-preview tags: the privacy page's block, pointed at
  // this page (its own address, title and description).
  .replace(/<link rel="canonical" href="[^"]*" \/>/, '<link rel="canonical" href="https://www.outlastretirement.com/premium" />')
  .replace(/(property="og:url" content=")[^"]*/, '$1https://www.outlastretirement.com/premium')
  .replace(/((?:property="og:title"|name="twitter:title") content=")[^"]*/g, '$1Free and Premium — OutlastRetirement')
  .replace(/((?:property="og:description"|name="twitter:description") content=")[^"]*/g, '$1What the free OutlastRetirement planner includes, and what the optional Premium adds. Both run on your device.')
  .replace(/  <!-- This page used to carry[\s\S]*?-->\n/, '  <!-- GENERATED by scripts/generatePremiumPage.mjs from src/config/freeOffering.js\n       and src/config/premiumOffering.js. Edit those, then run the script. -->\n')
  .replace('</style>', `    .tiers { display: grid; gap: 16px; margin-top: 18px; }
    .tier { background: var(--panel); border: 1px solid var(--border); border-radius: 14px; padding: 18px 20px; }
    .tier h3 { font-size: 16px; margin: 0 0 4px; }
    .tier .blurb { color: var(--muted); font-size: 14px; margin: 0 0 10px; }
    .tier ul { margin: 0; }
    .tag { display: inline-block; font-size: 12px; font-weight: 700; letter-spacing: 0.06em; text-transform: uppercase; color: var(--accent-text); margin-bottom: 6px; }
    .mailto-note { display: flex; flex-wrap: wrap; align-items: center; gap: 10px; border: 1px solid var(--border); border-radius: 12px; padding: 10px 14px; margin: 8px 0 14px; color: var(--muted); font-size: 14px; line-height: 1.5; }
    .mailto-note--nothing { border-color: #e07a5f; }
    .mailto-note-text { flex: 1 1 260px; }
    .mailto-note strong { color: var(--text); }
    .btn-ghost { border: 2px solid var(--border); color: var(--text); }
  </style>`);

const list = (points) => `<ul>\n${points.map((p) => `          <li>${esc(p)}</li>`).join('\n')}\n        </ul>`;

const free = FREE_GROUPS.map((g) => `      <div class="tier">
        <h3>${esc(g.title)}</h3>
        ${list(g.points)}
      </div>`).join('\n');

const premium = PREMIUM_AREAS.map((a) => `      <div class="tier">
        <span class="tag">Premium</span>
        <h3>${esc(a.name)}</h3>
        <p class="blurb">${esc(a.tagline)}</p>
${a.features.map((f) => `        <p><strong>${esc(f.title)}.</strong> ${esc(f.blurb)}</p>
        ${list(f.points)}`).join('\n')}
      </div>`).join('\n');

const html = `${head}</head>
<body>
  <header class="nav">
    <div class="nav-inner">
      <a class="brand" href="/" aria-label="OutlastRetirement home">
        <img class="or-logo or-logo--full logo-on-dark" alt="OutlastRetirement" src="/brand/outlast-full-dark-h96.png" srcset="/brand/outlast-full-dark-h96.png 413w, /brand/outlast-full-dark.png 870w" sizes="121px" width="121" height="28" />
        <img class="or-logo or-logo--full logo-on-light" alt="OutlastRetirement" src="/brand/outlast-full-light-h96.png" srcset="/brand/outlast-full-light-h96.png 413w, /brand/outlast-full-light.png 870w" sizes="121px" width="121" height="28" />
      </a>
${SITE_NAV.map(({ href, label }) => `      <a class="${href === '/app/' ? 'btn btn-primary btn-sm' : 'navlink'}" href="${href}"${href === '/premium' ? ' aria-current="page"' : ''}>${label}</a>`).join('\n')}
    </div>
  </header>

  <div class="container">
    <div class="page-head">
      <h1>Free and Premium</h1>
    </div>

    <main>
    <div class="highlight">
      <p>The free planner answers the whole question: does your money outlast you? Premium is optional depth for people who want to track real holdings, work out their spending, see the working behind each Readiness answer, or plan a move abroad. Both run entirely on your device.</p>
    </div>

    <h2>Free</h2>
    <p>Everything below is free, with no account.</p>
    <div class="tiers">
${free}
    </div>

    <h2>Premium</h2>
    <p>One Premium, not a menu of add-ons. It is <strong>invite-only and free while we are in beta</strong>: there is no checkout and no payment. You are invited. Email <a href="mailto:${esc(CONTACT_EMAIL)}?subject=Premium%20access" data-mailto-fallback>${esc(CONTACT_EMAIL)}</a> from your usual email and we will send the steps to turn it on; nothing is sent from this page. An access key lasts 30 days and is renewed by email.</p>
    <div class="tiers">
${premium}
    </div>

    <h2>Questions</h2>
    <p><strong>Does Premium change the projection?</strong> No. Free and Premium run the same calculations. Premium adds detail around them, and a few Premium features can fill plan fields from your holdings or spending when you choose to link them.</p>
    <p><strong>Is anything sent anywhere?</strong> Not your plan. Your plan, holdings and spending stay in your browser in both. Two optional features, both off by default, send something when you turn them on: Live Pricing sends ticker symbols (never amounts) to a Google Sheet you own, whose script looks them up with Google Finance and Yahoo Finance from Google&rsquo;s servers; and Anonymous Usage Analytics sends ${esc(ANALYTICS_SENDS)} The <a href="/privacy">Privacy Policy</a> says exactly what each sends.</p>
    <p><strong>Is this advice?</strong> No. OutlastRetirement is educational software, not financial, tax or legal advice.</p>
    <p><a href="/app/?demo=1">Try the demo plan</a> to see both, including a read-only preview of Premium&rsquo;s Detailed Holdings.</p>
    </main>

    <footer>
      <p><strong>Local-first retirement education. Your numbers never leave your device.</strong></p>
      <nav class="foot-links" aria-label="Site links"><a href="/">Home</a> <a href="/learn">Learn</a> <a href="/how-the-math-works">How the math works</a> <a href="/changelog">Release notes</a> <a href="/privacy">Privacy</a> <a href="/terms">Terms</a> <a href="/accessibility">Accessibility</a> <a href="/verify">Verify it yourself</a> <a href="/premium">Free and Premium</a> <a href="mailto:hello@outlastretirement.com">Contact</a> <a href="/app/">Open the app</a></nav>
      <p>© 2026 OutlastRetirement LLC. All rights reserved.</p>
    </footer>
  </div>
  <script src="/mailto-fallback.js"></script>
</body>
</html>
`;

const out = join(root, 'public/premium.html');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== html) { console.error('public/premium.html is stale: run node scripts/generatePremiumPage.mjs'); process.exit(1); }
  console.log('premium.html is current');
} else {
  writeFileSync(out, html);
  console.log('wrote public/premium.html');
}
